// Converts Android AntennaPod 3.12.1's vector drawables (ui/common's ic_*.xml,
// read from the NotTennaPod-Android checkout at tag 3.12.1) into
// src/generated/icons.ts, so the browser shows Android's icons, never
// redrawn ones. Theme colours become currentColor.
import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const android = process.env.NTP_ANDROID ?? join(root, "..", "NotTennaPod-Android");
const tag = "3.12.1";
const dir = "ui/common/src/main/res/drawable/";

const attr = (el, name) => {
  const m = new RegExp(`android:${name}="([^"]*)"`).exec(el);
  return m ? m[1] : undefined;
};

export function convert(xml) {
  const vw = Number(attr(xml, "viewportWidth"));
  const vh = Number(attr(xml, "viewportHeight"));
  if (!vw || !vh) return null;
  const out = [];
  const stack = [];
  for (const m of xml.matchAll(/<(\/?)(group|path|clip-path)\b([^>]*?)(\/?)>/gs)) {
    const [, close, tag, attrs, selfClose] = m;
    if (tag === "group") {
      if (close) stack.pop();
      else {
        const t = [];
        const tx = Number(attr(attrs, "translateX") ?? 0), ty = Number(attr(attrs, "translateY") ?? 0);
        const px = Number(attr(attrs, "pivotX") ?? 0), py = Number(attr(attrs, "pivotY") ?? 0);
        const r = Number(attr(attrs, "rotation") ?? 0);
        const sx = Number(attr(attrs, "scaleX") ?? 1), sy = Number(attr(attrs, "scaleY") ?? 1);
        if (tx || ty) t.push(`translate(${tx} ${ty})`);
        if (r) t.push(`rotate(${r} ${px} ${py})`);
        if (sx !== 1 || sy !== 1) t.push(`translate(${px} ${py}) scale(${sx} ${sy}) translate(${-px} ${-py})`);
        if (!selfClose) stack.push(t.join(" "));
      }
      continue;
    }
    if (tag !== "path" || close) continue;
    const d = attr(attrs, "pathData");
    if (!d) continue;
    const fill = attr(attrs, "fillColor");
    const stroke = attr(attrs, "strokeColor");
    const p = { d };
    const colour = (c) => (!c || c.startsWith("?") || c.startsWith("@") ? "currentColor" : c);
    p.fill = fill === undefined ? "none" : colour(fill);
    if (stroke !== undefined) {
      p.stroke = colour(stroke);
      p.strokeWidth = Number(attr(attrs, "strokeWidth") ?? 1);
    }
    if (attr(attrs, "fillType") === "evenOdd") p.fillRule = "evenodd";
    const alpha = attr(attrs, "fillAlpha");
    if (alpha !== undefined) p.opacity = Number(alpha);
    const transform = stack.filter(Boolean).join(" ");
    if (transform) p.transform = transform;
    out.push(p);
  }
  return { viewBox: `0 0 ${vw} ${vh}`, paths: out };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (!existsSync(android)) {
    console.error(`icons: ${android} not found (set NTP_ANDROID)`);
    process.exit(1);
  }
  const names = execFileSync("git", ["-C", android, "ls-tree", "--name-only", `${tag}:${dir}`], { encoding: "utf8" })
    .split("\n")
    .filter((n) => /^ic_[a-z0-9_]+\.xml$/.test(n));
  const icons = {};
  for (const n of names.sort()) {
    const xml = execFileSync("git", ["-C", android, "show", `${tag}:${dir}${n}`], { encoding: "utf8" });
    if (!xml.includes("<vector")) continue;
    const icon = convert(xml);
    if (icon && icon.paths.length) icons[n.slice(3, -4)] = icon;
  }
  const lines = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  writeFileSync(
    join(root, "src", "generated", "icons.ts"),
    [
      `// Generated by scripts/icons.mjs from Android AntennaPod ${tag}'s vector drawables (${dir}). Do not edit.`,
      "export interface IconPath { d: string; fill: string; stroke?: string; strokeWidth?: number; fillRule?: string; opacity?: number; transform?: string }",
      "export const icons = {",
      ...lines,
      "} satisfies Record<string, { viewBox: string; paths: IconPath[] }>;",
      "",
      "export type IconName = keyof typeof icons;",
      "",
    ].join("\n"),
  );
  console.log(`icons: ${Object.keys(icons).length} icons`);
}
